// ---------------------------------------------------------------- aggregation

/** FAILED > NOT RUN > BLOCKED > PASSED; an empty list is NOT RUN; AWS-only stays AWS. */
export function combine(list) {
  if (list.length === 0) return res(S.NOT_RUN, ['nothing is mapped']);
  const pick = (set) => set.flatMap((r) => r.detail || []);
  const counts = { total: list.reduce((n, r) => n + (r.counts?.total || 0), 0) };
  const live = list.filter((r) => r.s !== S.AWS);
  const open = pick(list.filter((r) => r.s !== S.PASSED));
  if (live.length === 0) return res(S.AWS, open, { counts });
  for (const s of [S.FAILED, S.NOT_RUN]) if (live.some((r) => r.s === s)) return res(s, open, { counts });
  const blocked = live.filter((r) => r.s === S.BLOCKED);
  if (blocked.length) {
    const reasons = [...new Set(blocked.map((r) => r.reason || 'unspecified'))];
    return res(S.BLOCKED, open, { reason: reasons.join('; '), counts });
  }
  return res(S.PASSED, pick(list), { counts });
}

// ---------------------------------------------------------------- unit (JUnit XML)

const unescapeXml = (s) => s
  .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;/g, "'")
  .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
  .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
  .replace(/&amp;/g, '&');

// node:test escapes "&" a second time (a quote is written "&amp;quot;"), so a quote and a literal "&quot;"
// read the same. Recorded names and scanned titles are both decoded until stable, which makes them comparable.
const decodeAll = (s) => { let prev; do { prev = s; s = unescapeXml(s); } while (s !== prev); return s; };

/** node:test junit reporter -> [{ name, status: passed|failed|skipped, message }]. */
export function parseJunit(xml) {
  const cases = [];
  // The reporter leaves ">" unescaped inside attribute values ("year > 2017"), so skip quoted strings.
  const re = /<testcase\b((?:[^>"]|"[^"]*")*?)(\/>|>([\s\S]*?)<\/testcase>)/g;
  let m;
  while ((m = re.exec(xml))) {
    const name = /\bname="([^"]*)"/.exec(m[1]);
    const body = m[3] || '';
    let status = 'passed';
    let message = '';
    const bad = /<(failure|error)\b([^>]*)/.exec(body);
    const skip = /<skipped\b([^>]*)/.exec(body);
    if (bad) { status = 'failed'; message = unescapeXml((/message="([^"]*)"/.exec(bad[2]) || [])[1] || bad[1]); }
    else if (skip) { status = 'skipped'; message = unescapeXml((/message="([^"]*)"/.exec(skip[1]) || [])[1] || ''); }
    cases.push({ name: decodeAll(name ? name[1] : ''), status, message });
  }
  return cases;
}

/** Static scan of a test file: one anchored regex per test()/it() title (`${...}` -> `.*`). */
export function scanTitles(source) {
  const out = [];
  const re = /^[ \t]*(?:test|it)(?:\.(?:skip|todo|only))?\(\s*(['"`])((?:\\[\s\S]|(?!\1)[^\\])*)\1/gm;
  let m;
  while ((m = re.exec(source))) {
    const parts = m[2].split(/\$\{[^}]*\}/);
    const dynamic = parts.length > 1;
    const unescape = (p) => decodeAll(p.replace(/\\(.)/g, '$1'));
    const sample = parts.map(unescape).join('');
    // A dynamic title with fewer than 8 literal characters would match tests of other files: never used.
    const weak = dynamic ? sample.trim().length < 8 : sample.length === 0;
    const body = parts.map((p) => unescape(p).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('.*');
    out.push({ title: sample, dynamic, weak, regex: new RegExp(`^${body}$`) });
  }
  return out;
}

export const titlePatterns = (source) => scanTitles(source).filter((e) => !e.weak).map((e) => e.regex);

const listFiles = (dir, suffix) => (fs.existsSync(dir) ? fs.readdirSync(dir).filter((n) => n.endsWith(suffix)).sort() : []);
const shown = (list) => `${list.slice(0, 5).map((t) => `"${t}"`).join(', ')}${list.length > 5 ? `, ... ${list.length - 5} more` : ''}`;

/** Which unit file owns each recorded case: exactly one file's patterns must match, else it is ambiguous or unowned. */
export function unitIndex(unitDir, cases) {
  const byFile = new Map(); // strong titles: used to attribute a case to a file
  const weakByFile = new Map(); // weak titles: never used for ownership, but still required to have a record
  for (const f of listFiles(unitDir, '.test.mjs')) {
    const all = scanTitles(fs.readFileSync(path.join(unitDir, f), 'utf8'));
    byFile.set(f, all.filter((e) => !e.weak));
    weakByFile.set(f, all.filter((e) => e.weak));
  }
  const owner = [];
  const weakOwner = []; // an otherwise unowned case claimed by exactly one file's weak pattern
  const ambiguous = [];
  const unowned = [];
  cases.forEach((c, i) => {
    const owners = [...byFile].filter(([, es]) => es.some((e) => e.regex.test(c.name))).map(([f]) => f);
    owner[i] = owners.length === 1 ? owners[0] : null;
    weakOwner[i] = null;
    if (owners.length > 1) ambiguous.push({ name: c.name, files: owners, status: c.status });
    if (owners.length === 0) {
      const weak = [...weakByFile].filter(([, es]) => es.some((e) => e.regex.test(c.name))).map(([f]) => f);
      if (weak.length === 1) weakOwner[i] = weak[0];
      else unowned.push({ name: c.name, status: c.status, ...(weak.length > 1 ? { weakFiles: weak } : {}) });
    }
  });
  return { byFile, weakByFile, owner, weakOwner, ambiguous, unowned };
}

function evalUnit(ref, ctx) {
  if (!ctx.unit) return res(S.NOT_RUN, ['no unit report (reports/unit.xml)']);
  const idx = (ctx.unitIdx ||= unitIndex(ctx.unitDir, ctx.unit));
  const entries = [...(idx.byFile.get(ref.file) || []), ...(idx.weakByFile.get(ref.file) || [])];
  if (!idx.byFile.has(ref.file)) return res(S.NOT_RUN, [`unit file not found: ${ref.file}`]);
  const filter = new RegExp(ref.match || '.');
  const mine = ctx.unit.filter((c, i) => idx.owner[i] === ref.file || idx.weakOwner[i] === ref.file);
  const hit = mine.filter((c) => filter.test(c.name));
  const min = ref.min ?? 1;
  const counts = { total: hit.length };
  // FR-25 BUT: every test the file declares inside this ref's match must have a recorded case.
  const expected = entries.filter((e) => filter.test(e.title));
  // A case owned through a strong title satisfies its pattern whatever its status (a skipped one is NOT RUN below);
  // an unowned case claimed through a weak pattern satisfies it only when it PASSED.
  const missing = expected.filter((e) => !mine.some((c) => e.regex.test(c.name) && (e.dynamic || filter.test(c.name))
    && (!e.weak || idx.owner[ctx.unit.indexOf(c)] === ref.file || c.status === 'passed')));
  const failed = hit.filter((c) => c.status === 'failed');
  if (failed.length) return res(S.FAILED, failed.map((c) => `${ref.file}: ${c.name}`), { counts }); // FAILED outranks a gap
  if (hit.length < min || missing.length) {
    const why = missing.length ? `${missing.length} declared test(s) have no recorded case: ${shown(missing.map((e) => e.title))}` : `${hit.length} recorded, ${min} required`;
    return res(S.NOT_RUN, [`${ref.file} /${ref.match || '.'}/: ${why}`], { counts });
  }
  const skipped = hit.filter((c) => c.status === 'skipped');
  if (skipped.length) return res(S.NOT_RUN, skipped.map((c) => `${ref.file}: skipped ${c.name}${c.message ? ` (${c.message})` : ''}`), { counts });
  return res(S.PASSED, [], { counts });
}

// ---------------------------------------------------------------- e2e (Playwright JSON)

export const classOf = (annotations = []) => {
  const found = annotations.filter((a) => a.type === 'class').map((a) => String(a.description || ''));
  const valid = found.map((d) => CLASSES.find((c) => new RegExp(`^${c}(?![A-Za-z-])`).test(d))).filter(Boolean);
  return { declared: found, valid: [...new Set(valid)], ok: found.length === 1 && valid.length === 1 };
};

/** One cell per (test, project): { s, reason } or { na: reason }. */
export function cellOf(test) {
  const results = test.results || [];
  const last = results[results.length - 1];
  const ann = [...(test.annotations || []), ...(last?.annotations || [])];
  const cls = classOf(test.annotations?.length ? test.annotations : last?.annotations);
  const find = (t) => ann.find((a) => a.type === t);
  if (!last) return { s: S.NOT_RUN, reason: 'no execution record', cls };
  if (last.status === 'failed' || last.status === 'timedOut' || last.status === 'interrupted') return { s: S.FAILED, reason: last.status, cls };
  if (test.status === 'flaky') return { s: S.FAILED, reason: 'flaky: passed only on retry', cls };
  if (cls.valid.includes('AWS')) return { s: S.AWS, cls };
  const na = find('not-applicable');
  if (last.status === 'skipped' && na) return { na: String(na.description || 'not applicable'), cls };
  const blocked = find('blocked');
  if (blocked) return { s: S.BLOCKED, reason: String(blocked.description || 'unspecified'), cls };
  if (last.status === 'skipped') return { s: S.NOT_RUN, reason: 'skipped without a blocked or not-applicable annotation', cls };
  if (last.status === 'passed') return { s: S.PASSED, cls };
  return { s: S.NOT_RUN, reason: `unknown status ${last.status}`, cls };
}

/** Flatten the Playwright JSON report into groups keyed by file + full title. */
export function flattenE2E(report) {
  const projects = (report.config?.projects || []).map((p) => p.name);
  const groups = new Map();
  const walk = (suite, titles) => {
    for (const spec of suite.specs || []) {
      for (const t of spec.tests || []) {
        const key = `${spec.file}::${[...titles, spec.title].join(' > ')}`;
        if (!groups.has(key)) groups.set(key, { file: spec.file, title: spec.title, full: [...titles, spec.title].join(' > '), cells: {} });
        groups.get(key).cells[t.projectName || ''] = cellOf(t);
      }
    }
    for (const child of suite.suites || []) {
      walk(child, child.title && child.title !== child.file && child.title !== suite.file ? [...titles, child.title] : titles);
    }
  };
  for (const s of report.suites || []) walk(s, []);
  const seen = new Set();
  for (const g of groups.values()) for (const p of Object.keys(g.cells)) seen.add(p);
  const all = projects.length ? projects : [...seen];
  return { groups: [...groups.values()], projects: all };
}

/** One test across browsers: NOT APPLICABLE cells are excluded, but one browser must have PASSED. */
export function groupStatus(group, projects) {
  const cells = projects.map((p) => ({ project: p, ...(group.cells[p] || { s: S.NOT_RUN, reason: `no result for project ${p}` }) }));
  const na = cells.filter((c) => c.na !== undefined).map((c) => `NOT APPLICABLE (by spec: ${c.na})`);
  const live = cells.filter((c) => c.na === undefined);
  const name = `${group.file}: ${group.full}`;
  if (live.length === 0) return res(S.NOT_RUN, [`${name}: every browser is not-applicable, nothing exercised the behavior`], { na });
  const bad = (s) => live.filter((c) => c.s === s);
  const where = (list) => list.map((c) => `${c.project}${c.reason ? ` ${c.reason}` : ''}`).join(', ');
  if (bad(S.FAILED).length) return res(S.FAILED, [`${name}: FAILED in ${where(bad(S.FAILED))}`], { na });
  if (bad(S.NOT_RUN).length) return res(S.NOT_RUN, [`${name}: NOT RUN in ${where(bad(S.NOT_RUN))}`], { na });
  const blocked = bad(S.BLOCKED);
  if (blocked.length) {
    const reasons = [...new Set(blocked.map((c) => c.reason))];
    return res(S.BLOCKED, [`${name}: BLOCKED (${reasons.join('; ')}) in ${blocked.map((c) => c.project).join(', ')}`], { reason: reasons.join('; '), na });
  }
  if (live.every((c) => c.s === S.AWS)) return res(S.AWS, [], { na });
  if (!live.some((c) => c.s === S.PASSED)) return res(S.NOT_RUN, [`${name}: no browser PASSED`], { na });
  return res(S.PASSED, [], { na });
}

/** Declared tests of a spec file that no recorded group (any project) matches. */
function missingE2E(file, ctx) {
  const p = path.join(ctx.e2eDir, file);
  if (!fs.existsSync(p)) return { notFound: true, missing: [] };
  const entries = scanTitles(fs.readFileSync(p, 'utf8')); // weak titles count: groups are scoped by file, so no collision
  const groups = ctx.e2e.groups.filter((g) => g.file === file);
  return { missing: entries.filter((e) => !groups.some((g) => e.regex.test(g.title))).map((e) => e.title) };
}

/** A class-wide verdict means nothing while a declared test of any spec file has no record. */
function gapsE2E(ctx) {
  const lines = [];
  for (const f of listFiles(ctx.e2eDir, '.spec.mjs')) {
    const { missing } = missingE2E(f, ctx);
    if (missing.length) lines.push(`${f}: ${missing.length} declared test(s) have no record in any browser: ${shown(missing)}`);
  }
  return lines;
}

function evalE2E(ref, ctx) {
  if (!ctx.e2e) return res(S.NOT_RUN, ['no Playwright report (reports/e2e/results.json)']);
  const { notFound, missing } = missingE2E(ref.file, ctx);
  if (notFound) return res(S.NOT_RUN, [`spec file not found: ${ref.file}`]);
  const re = ref.match ? new RegExp(ref.match) : null;
  const hit = ctx.e2e.groups.filter((g) => g.file === ref.file && (!re || re.test(g.title) || re.test(g.full)));
  const min = ref.min ?? 1;
  const counts = { total: hit.length };
  // FR-25 BUT: a spec file runs whole, so every test it declares must have a record.
  const parts = hit.map((g) => groupStatus(g, ctx.e2e.projects));
  const gap = [];
  if (missing.length) gap.push(`${ref.file}: ${missing.length} declared test(s) have no record in any browser: ${shown(missing)}`);
  else if (hit.length < min) gap.push(`${ref.file}${ref.match ? ` /${ref.match}/` : ''}: ${hit.length} recorded, ${min} required`);
  if (gap.length) parts.push(res(S.NOT_RUN, gap)); // combine(): FAILED outranks the gap
  const out = combine(parts);
  out.na = parts.flatMap((p) => p.na || []);
  out.counts = counts;
  return out;
}

function evalE2EClass(ref, ctx) {
  if (!ctx.e2e) return res(S.NOT_RUN, ['no Playwright report (reports/e2e/results.json)']);
  const gaps = gapsE2E(ctx);
  const hit = ctx.e2e.groups.filter((g) => Object.values(g.cells).some((c) => c.cls?.valid.includes(ref.class)));
  const parts = hit.map((g) => groupStatus(g, ctx.e2e.projects));
  if (gaps.length) parts.push(res(S.NOT_RUN, gaps)); // combine(): a recorded FAILED outranks the gap
  else if (hit.length === 0) parts.push(res(S.NOT_RUN, [`no ${ref.class} test recorded`]));
  const out = combine(parts);
  out.counts = { total: hit.length };
  return out;
}

/** FR-27: every recorded e2e test declares exactly one class. Unit suites are LOCAL by design 10.1. */
function evalFr27(ctx) {
  if (!ctx.e2e) return res(S.NOT_RUN, ['no Playwright report (reports/e2e/results.json)']);
  const gaps = gapsE2E(ctx);
  const bad = [];
  let total = 0;
  for (const g of ctx.e2e.groups) {
    for (const [project, c] of Object.entries(g.cells)) {
      total += 1;
      if (!c.cls.ok) bad.push(`${g.file}: ${g.full} [${project}]: class annotations ${JSON.stringify(c.cls.declared)} (exactly one of ${CLASSES.join('/')} required)`);
    }
  }
  if (total === 0) return res(S.NOT_RUN, ['the report holds no test']);
  const parts = [];
  if (bad.length) parts.push(res(S.FAILED, bad));
  if (gaps.length) parts.push(res(S.NOT_RUN, gaps)); // combine(): a recorded FAILED outranks the gap
  if (parts.length === 0) return res(S.PASSED, [], { counts: { total } });
  const out = combine(parts);
  out.counts = { total };
  return out;
}

// ---------------------------------------------------------------- compare report

function evalCompare(ref, ctx) {
  const r = ctx.compare;
  if (!r) return res(S.NOT_RUN, ['no compare report (reports/compare/report.json)']);
  switch (ref.rule) {
    case 'r1': {
      const x = r.r1;
      if (!x || !(x.total > 0)) return res(S.NOT_RUN, ['compare report has no R1 result']);
      if (x.differing === 0 && x.matched === x.total) return res(S.PASSED, [], { counts: { total: x.total } });
      return res(S.FAILED, [`R1: ${x.differing} of ${x.total} cases differ ${JSON.stringify(x.byCategory || {})}`], { counts: { total: x.total } });
    }
    case 'r2': {
      const x = r.r2;
      if (!x || !x.status) return res(S.NOT_RUN, ['compare report has no R2 result']);
      return x.status === 'GENERATED' ? res(S.PASSED, ['R2 page generated; the visual review itself is human (NFR-08)']) : res(S.FAILED, [`R2 ${x.status}: ${x.detail || ''}`]);
    }
    case 'r3': {
      const x = r.r3;
      if (!x || !x.status) return res(S.NOT_RUN, ['compare report has no R3 result']);
      const blocked = /^BLOCKED \((.*)\)$/.exec(x.status);
      if (blocked) return res(S.BLOCKED, [`R3 ${x.status}`], { reason: blocked[1] });
      if (x.status === 'COMPARED (equal)') return res(S.PASSED);
      return res(S.FAILED, [`R3 ${x.status}: differences must be classified in E-06`]);
    }
    case 'limits': {
      const st = r.statements?.['FR-23 (AND IT MUST)'];
      if (typeof st === 'string' && st.trim() && Array.isArray(r.declaredLimits) && r.declaredLimits.length) return res(S.PASSED);
      return res(S.FAILED, ['the compare report must state the R1 limit (statements["FR-23 (AND IT MUST)"]) and list declaredLimits']);
    }
    default: return res(S.NOT_RUN, [`unknown compare rule ${ref.rule}`]);
  }
}

// ---------------------------------------------------------------- NFR-04 (build-history.jsonl)

export function parseHistory(text) {
  const records = [];
  const bad = [];
  text.split(/\r?\n/).forEach((line, i) => {
    if (!line.trim()) return;
    try { records.push({ ...JSON.parse(line), _line: i + 1 }); } catch { bad.push(i + 1); }
  });
  return { records, bad };
}

/** Design 10.3: every clean build counts, whatever budget or source recorded it (a budgetMs 1 falsifier run is a real, harmless ~1 s build). */
export const countsForNfr04 = (r) => r.clean !== false && typeof r.elapsedMs === 'number';

/**
 * Any clean build with elapsedMs above the budget is FAILED unless a LATER counted record with
 * idle: true passes. Nothing is ever deleted from the history.
 */
export function evalBuildTime(history, budgetMs) {
  if (!history) return res(S.NOT_RUN, ['no build history (artifacts/build-history.jsonl)']);
  const real = history.records.filter(countsForNfr04);
  const note = `${real.length} clean record(s) counted against ${budgetMs} ms; ${history.records.length - real.length} not counted (not clean, or no elapsedMs)`;
  if (real.length === 0) return res(S.NOT_RUN, [`no clean timing record: ${note}`]);
  const failures = [];
  const overridden = [];
  real.forEach((r, i) => {
    if (r.elapsedMs <= budgetMs) return;
    const rescue = real.slice(i + 1).find((x) => x.idle === true && x.elapsedMs <= budgetMs);
    (rescue ? overridden : failures).push(r);
  });
  const fmt = (r) => `${r.timestamp || `line ${r._line}`}: ${r.elapsedMs} ms > ${budgetMs} ms${r.idle ? ' (idle)' : ''}`;
  const detail = [note, ...overridden.map((r) => `overridden by a later passing idle record: ${fmt(r)}`)];
  if (failures.length) return res(S.FAILED, [...failures.map((r) => `build time FAILED: ${fmt(r)}`), ...detail], { counts: { total: real.length } });
  const max = Math.max(...real.map((r) => r.elapsedMs));
  return res(S.PASSED, [`${detail[0]}; slowest ${max} ms`, ...detail.slice(1)], { counts: { total: real.length } });
}

// ---------------------------------------------------------------- criteria

function evalRule(ref, ctx) {
  switch (ref.rule) {
    case 'fr27': return evalFr27(ctx);
    case 'build-time': return evalBuildTime(ctx.history, ctx.budgetMs);
    case 'node-engines': {
      if (!ctx.unit) return res(S.NOT_RUN, ['no unit report: the Node version of an executed run is unknown']);
      const v = ctx.env?.node || process.version;
      const ok = /^v22\.(\d+)\./.test(v) && Number(/^v22\.(\d+)\./.exec(v)[1]) >= 12;
      return ok ? res(S.PASSED, [`Node ${v} satisfies engines >=22.12.0 <23`]) : res(S.FAILED, [`Node ${v} is outside engines >=22.12.0 <23`]);
    }
    default: return res(S.NOT_RUN, [`unknown rule ${ref.rule}`]);
  }
}

/**
 * Manual intake: <manual dir>/<criterion-id>.json = { id, status, evidenceFiles, recordedAt, recordedBy, command(s) }.
 * Accepted only when every evidence file exists under the evidence root and is non-empty; otherwise the
 * criterion stays NOT RUN. The record is one more mapped source: combine() still lets an automated
 * FAILED win, and an automated NOT RUN keeps the criterion NOT RUN.
 */
export function evalManual(ref, ctx, id) {
  const pending = res(S.NOT_RUN, [], { manualPending: ref.note });
  const entry = ctx.manual?.[id];
  if (!entry) return pending;
  const bad = (msg) => res(S.NOT_RUN, [`manual record for ${id}: ${msg}`], { manualPending: ref.note });
  if (entry.error) return bad(entry.error);
  const rec = entry.record;
  if (!rec || rec.id !== id) return bad(`id must be "${id}"`);
  const m = /^(PASSED|FAILED|NOT RUN|BLOCKED \((.+)\))$/.exec(String(rec.status));
  if (!m) return bad('status must be PASSED, FAILED, BLOCKED (reason) or NOT RUN');
  for (const f of ['recordedAt', 'recordedBy']) if (typeof rec[f] !== 'string' || !rec[f].trim()) return bad(`${f} is required`);
  if (!(typeof rec.command === 'string' && rec.command.trim()) && !(Array.isArray(rec.commands) && rec.commands.length)) return bad('command or commands is required');
  const files = rec.evidenceFiles;
  if (!Array.isArray(files) || files.length === 0) return bad('manual record without evidence file');
  const root = path.resolve(ctx.evidenceRoot || '.');
  for (const f of files) {
    const abs = path.resolve(root, String(f));
    const inside = abs === root || abs.startsWith(root + path.sep);
    if (!inside || !fs.existsSync(abs) || !fs.statSync(abs).isFile() || fs.statSync(abs).size === 0) return bad(`manual record without evidence file (${f})`);
  }
  const status = m[1] === 'NOT RUN' ? S.NOT_RUN : m[1].startsWith('BLOCKED') ? S.BLOCKED : m[1];
  return res(status, [`manual (recorded by ${rec.recordedBy} at ${rec.recordedAt}): ${m[1]}`], { reason: m[2], manualFiles: files, counts: { total: 0 } });
}

function evalRef(ref, ctx, byId, stack) {
  switch (ref.type) {
    case 'unit': return evalUnit(ref, ctx);
    case 'e2e': return evalE2E(ref, ctx);
    case 'e2e-class': return evalE2EClass(ref, ctx);
    case 'compare': return evalCompare(ref, ctx);
    case 'rule': return evalRule(ref, ctx);
    case 'manual': return evalManual(ref, ctx, stack[stack.length - 1]);
    case 'criteria': {
      const parts = ref.ids.map((id) => evalCriterion(id, ctx, byId, stack));
      return combine(parts);
    }
    default: return res(S.NOT_RUN, [`unknown reference type ${ref.type}`]);
  }
}

function evalCriterion(id, ctx, byId, stack = []) {
  const c = byId.get(id);
  if (!c) return res(S.NOT_RUN, [`${id} is not in traceability.json`]);
  if (ctx.cache.has(id)) return ctx.cache.get(id);
  if (stack.includes(id)) return res(S.NOT_RUN, [`cycle through ${id}`]);
  const parts = (c.refs || []).map((ref) => {
    const r = evalRef(ref, ctx, byId, [...stack, id]);
    return { ...r, ref };
  });
  const out = combine(parts);
  out.na = parts.flatMap((p) => p.na || []);
  out.manual = parts.filter((p) => p.manualPending !== undefined).map((p) => p.manualPending);
  out.manualFiles = parts.flatMap((p) => p.manualFiles || []);
  ctx.cache.set(id, out);
  return out;
}

export function validateTraceability(t) {
  const errors = [];
  if (!t || !Array.isArray(t.criteria)) return ['traceability.json needs a "criteria" array'];
  const ids = new Set();
  const types = new Set(['unit', 'e2e', 'e2e-class', 'compare', 'rule', 'manual', 'criteria']);
  for (const c of t.criteria) {
    if (!c.id || ids.has(c.id)) errors.push(`duplicate or missing id ${c.id}`);
    ids.add(c.id);
    if (!Array.isArray(c.refs) || c.refs.length === 0) errors.push(`${c.id}: no refs`);
    for (const r of c.refs || []) {
      if (!types.has(r.type)) errors.push(`${c.id}: unknown ref type ${r.type}`);
      if ((r.type === 'unit' || r.type === 'e2e') && !r.file) errors.push(`${c.id}: ${r.type} ref without file`);
      if (r.type === 'criteria') for (const x of r.ids || []) if (!t.criteria.some((o) => o.id === x)) errors.push(`${c.id}: refers to unknown ${x}`);
    }
  }
  const need = [
    ...Array.from({ length: 15 }, (_, i) => `AC-L${String(i + 1).padStart(2, '0')}`),
    ...Array.from({ length: 29 }, (_, i) => `FR-${String(i + 1).padStart(2, '0')}`),
    ...Array.from({ length: 12 }, (_, i) => `NFR-${String(i + 1).padStart(2, '0')}`),
  ];
  for (const id of need) if (!ids.has(id)) errors.push(`${id} is missing`);
  return errors;
}

/** Pure core: traceability + parsed inputs -> per-criterion status. */
export function evaluate({ traceability, unit, e2e, compare, history, budgetMs = 60000, unitDir, e2eDir = path.join(ROOT, 'tests', 'e2e'), env, manual, evidenceRoot }) {
  const byId = new Map(traceability.criteria.map((c) => [c.id, c]));
  const ctx = { unit, e2e, compare, history, budgetMs, unitDir, e2eDir, env, manual, evidenceRoot, cache: new Map() };
  const rows = traceability.criteria.map((c) => {
    const r = evalCriterion(c.id, ctx, byId);
    return { id: c.id, kind: c.kind, title: c.title, class: c.class, command: c.command, awsPending: c.awsPending || [], ...r, status: label(r) };
  });
  const counts = {};
  for (const r of rows) counts[r.s] = (counts[r.s] || 0) + 1;
  const attribution = unit ? (ctx.unitIdx ||= unitIndex(unitDir, unit)) : null;
  return { rows, counts, attribution };
}

/** Exit rule: FAILED or NOT RUN (or a missing required report, which makes criteria NOT RUN). */
export function exitCode(rows, missingReports = []) {
  const bad = rows.some((r) => r.s === S.FAILED || r.s === S.NOT_RUN);
  return bad || missingReports.length ? 1 : 0;
}

