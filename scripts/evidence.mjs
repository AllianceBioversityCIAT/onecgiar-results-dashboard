const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const order = [S.PASSED, S.FAILED, S.BLOCKED, S.NOT_RUN, S.AWS];

export function renderSummary({ rows, counts, meta, raw, history, e2eClasses, budgetMs, attribution }) {
  const L = [];
  const total = rows.length;
  L.push(`# Evidence summary ${meta.date}`, '');
  L.push('> Generated by `npm run evidence` (`scripts/evidence.mjs`) from the raw reports under `raw/`. Do not edit by hand: a hand-edited file is not evidence.', '');
  L.push(`${total} criteria: ` + order.map((s) => `${counts[s] || 0} ${s}`).join(', ') + '.', '');
  L.push('| Field | Value |', '|---|---|');
  L.push(`| Generated at | ${meta.generatedAt} |`, `| Command | \`${meta.command}\` |`, `| Git commit | ${meta.git} |`);
  L.push(`| Node / npm | ${meta.node} / ${meta.npm} |`, `| OS | ${meta.os} |`, `| Shell | ${cell(meta.shell)} |`);
  L.push(`| Browsers | ${cell(meta.browsers)} |`, `| dist/ manifest hash | ${meta.manifestHash} |`, '');
  L.push('Full environment: `environment.json`. Status vocabulary: `PASSED`, `FAILED`, `BLOCKED (reason)`, `NOT RUN`, `NOT RUN — AWS` (design 10.3). A criterion is `PASSED` only when every mapped test was recorded and passed.', '');

  for (const kind of ['AC-L', 'FR', 'NFR']) {
    const set = rows.filter((r) => r.kind === kind);
    L.push(`## ${kind === 'AC-L' ? 'Acceptance criteria (AC-L)' : kind === 'FR' ? 'Functional requirements (FR)' : 'Non-functional requirements (NFR)'}`, '');
    L.push('| ID | Criterion | Class | Command | Status | Recorded tests |', '|---|---|---|---|---|---|');
    for (const r of set) L.push(`| ${r.id} | ${cell(r.title || '')} | ${r.class || 'LOCAL'} | ${cell(r.command || '')} | ${cell(r.status)} | ${r.counts?.total ?? 0}${r.manualFiles?.length ? ` manual (evidence: ${cell(r.manualFiles.join(', '))})` : ''} |`);
    L.push('');
  }

  const open = rows.filter((r) => r.s !== S.PASSED);
  L.push('## Why a criterion is not PASSED', '');
  if (open.length === 0) L.push('Every criterion is PASSED.', '');
  for (const r of open) {
    L.push(`### ${r.id} — ${r.status}`, '');
    const lines = [...new Set(r.detail)];
    for (const d of lines.slice(0, MAX_DETAIL)) L.push(`- ${cell(d)}`);
    if (lines.length > MAX_DETAIL) L.push(`- ... ${lines.length - MAX_DETAIL} more in the raw reports`);
    for (const m of r.manual || []) L.push(`- awaiting a manual record (manual/${r.id}.json) with evidence files: ${cell(m)}`);
    if (lines.length === 0 && !(r.manual || []).length) L.push('- (no detail recorded)');
    L.push('');
  }

  const na = rows.flatMap((r) => (r.na || []).map((n) => [r.id, n]));
  L.push('## Not applicable by specification', '');
  if (na.length === 0) L.push('None recorded.', '');
  else {
    L.push('These browser cells are skipped by the spec (for example FR-10 scopes the sphere click to Chromium/Firefox). They are excluded from the status of the criterion, which still needs one browser that PASSED.', '');
    const uniq = [...new Set(na.map(([id, n]) => `${id}: ${n}`))];
    for (const u of uniq) L.push(`- ${cell(u)}`);
    L.push('');
  }

  const aws = rows.filter((r) => r.awsPending.length);
  L.push('## Pending for AWS (Phase 4)', '');
  if (aws.length === 0) L.push('None declared.', '');
  for (const r of aws) for (const p of r.awsPending) L.push(`- ${r.id}: ${cell(p)}`);
  if (aws.length) L.push('');

  L.push('## NFR-04 build time', '');
  if (!history) L.push('No `build-history.jsonl`: NOT RUN.', '');
  else {
    const real = history.records.filter(countsForNfr04);
    L.push(`Budget ${budgetMs} ms. ${history.records.length} record(s) in the history, ${real.length} counted (every clean build counts, whatever budgetMs or source recorded it); the others are not clean builds.`, '');
    L.push('| Timestamp | elapsedMs | budgetMs | idle | Source | Counted |', '|---|---|---|---|---|---|');
    for (const r of history.records.slice(-15)) L.push(`| ${r.timestamp || ''} | ${r.elapsedMs} | ${r.budgetMs} | ${r.idle ? 'yes' : 'no'} | ${r.source || 'build'} | ${countsForNfr04(r) ? 'yes' : 'no'} |`);
    if (history.records.length > 15) L.push(`| ... | | | | | ${history.records.length - 15} older record(s) in raw/build-history.jsonl |`);
    L.push('');
  }

  L.push('## Test classes recorded (FR-27)', '');
  if (!e2eClasses) L.push('No Playwright report: NOT RUN. Unit suites are `LOCAL` by design 10.1.', '');
  else {
    L.push('| Class | Playwright tests (per browser) |', '|---|---|');
    for (const c of [...CLASSES, 'missing or ambiguous']) L.push(`| ${c} | ${e2eClasses[c] || 0} |`);
    L.push('');
  }

  L.push('## Raw reports', '', 'Run time is the moment the report says it was produced, or the file modification time where the report carries none.', '', '| Report | Status | Run time | Run time source | SHA-256 | Bytes |', '|---|---|---|---|---|---|');
  for (const f of raw) L.push(`| \`${f.name}\` | ${f.present ? 'copied' : 'MISSING'} | ${f.ranAt || ''} | ${f.ranAtSource || ''} | ${f.sha256 ? f.sha256.slice(0, 16) : ''} | ${f.bytes ?? ''} |`);
  if (attribution) {
    L.push('', '### Unit case attribution', '');
    const failedAmb = attribution.ambiguous.filter((a) => a.status === 'failed').length;
    const failedUn = attribution.unowned.filter((a) => a.status === 'failed').length;
    L.push(`${attribution.ambiguous.length} recorded case(s) match the titles of more than one test file (${failedAmb} failed) and ${attribution.unowned.length} match none (${failedUn} failed). They count for no criterion; a failure among them still fails \`npm test\`.`);
    for (const a of [...attribution.ambiguous.map((x) => ({ ...x, why: `ambiguous: ${x.files.join(', ')}` })), ...attribution.unowned.map((x) => ({ ...x, why: 'unowned' }))].filter((x) => x.status !== 'passed').slice(0, 10)) L.push(`- ${a.status}: ${cell(a.name)} (${a.why})`);
    L.push('');
  }
  L.push('');
  return L.join('\n');
}

// ---------------------------------------------------------------- I/O

function arg(name, env, fallback, argv) {
  const i = argv.indexOf(`--${name}`);
  if (i >= 0 && argv[i + 1]) return argv[i + 1];
  return process.env[env] || fallback;
}
/** A path from a flag or variable resolves against the current directory; the default is already absolute. */
const given = (name, env, argv) => (argv.indexOf(`--${name}`) >= 0 && argv[argv.indexOf(`--${name}`) + 1]) || process.env[env] || '';
const pathArg = (name, env, fallbackAbs, argv) => { const g = given(name, env, argv); return g ? path.resolve(process.cwd(), g) : fallbackAbs; };
const readText = (p) => (fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null);
const sha = (buf) => crypto.createHash('sha256').update(buf).digest('hex');
const today = () => { const d = new Date(); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`; };

function probe(cmd, args, opts = {}) {
  if (process.env.EVIDENCE_SKIP_PROBES === '1') return 'not probed';
  try {
    return execFileSync(cmd, args, { encoding: 'utf8', timeout: 8000, stdio: ['ignore', 'pipe', 'ignore'], cwd: ROOT, ...opts }).trim();
  } catch { return 'unavailable'; }
}

function shellInfo() {
  const parts = [];
  if (process.platform === 'win32') {
    const ps = probe('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', '$PSVersionTable.PSVersion.ToString()']);
    parts.push(`powershell.exe ${ps}`);
    const pwsh = probe('pwsh', ['-NoProfile', '-NonInteractive', '-Command', '$PSVersionTable.PSVersion.ToString()']);
    parts.push(pwsh === 'unavailable' ? 'pwsh not installed' : `pwsh ${pwsh}`);
  } else parts.push(process.env.SHELL || 'unknown');
  return parts.join('; ');
}

function browsersInfo() {
  const p = path.join(ROOT, 'node_modules', 'playwright-core', 'browsers.json');
  const pkg = readText(path.join(ROOT, 'node_modules', '@playwright', 'test', 'package.json'));
  try {
    const list = JSON.parse(fs.readFileSync(p, 'utf8')).browsers.filter((b) => ['chromium', 'firefox', 'webkit'].includes(b.name));
    const v = pkg ? `@playwright/test ${JSON.parse(pkg).version}` : '@playwright/test unknown';
    return `${v}: ` + list.map((b) => `${b.name} ${b.browserVersion || ''} (rev ${b.revision})`.replace('  ', ' ')).join(', ');
  } catch { return 'unknown (playwright-core/browsers.json not found)'; }
}

/** When the report was produced: the report's own timestamp where it has one, else the file mtime. */
export function ranAt(name, text, stat) {
  const mtime = { at: stat.mtime.toISOString(), source: 'file mtime' };
  try {
    if (name === 'e2e/results.json') { const t = JSON.parse(text).stats?.startTime; if (t) return { at: t, source: 'Playwright stats.startTime' }; }
    if (name === 'compare/report.json') { const t = JSON.parse(text).generatedAt; if (t) return { at: t, source: 'compare generatedAt' }; }
    if (name === 'build-history.jsonl') {
      const last = parseHistory(text).records.at(-1);
      if (last?.timestamp) return { at: last.timestamp, source: 'last history record' };
    }
  } catch { /* fall back to the mtime */ }
  return mtime;
}

function copyRaw(reportsDir, artifactsDir, outDir) {
  const files = [
    ['unit.xml', path.join(reportsDir, 'unit.xml')],
    ['e2e/results.json', path.join(reportsDir, 'e2e', 'results.json')],
    ['compare/report.json', path.join(reportsDir, 'compare', 'report.json')],
    ['build-history.jsonl', path.join(artifactsDir, 'build-history.jsonl')],
    ['build-stats.json', path.join(artifactsDir, 'build-stats.json')],
    ['dist-manifest.json', path.join(artifactsDir, 'dist-manifest.json')],
  ];
  return files.map(([name, src]) => {
    if (!fs.existsSync(src)) return { name, present: false };
    const buf = fs.readFileSync(src);
    const dest = path.join(outDir, 'raw', name);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, buf);
    const stat = fs.statSync(src);
    const when = ranAt(name, buf.toString('utf8'), stat);
    return { name, present: true, sha256: sha(buf), bytes: buf.length, ranAt: when.at, ranAtSource: when.source };
  });
}

function classCounts(e2e) {
  if (!e2e) return null;
  const out = {};
  for (const g of e2e.groups) for (const c of Object.values(g.cells)) {
    const k = c.cls.ok ? c.cls.valid[0] : 'missing or ambiguous';
    out[k] = (out[k] || 0) + 1;
  }
  return out;
}

function loadManual(dir) {
  const out = {};
  if (!fs.existsSync(dir)) return out;
  for (const f of fs.readdirSync(dir).filter((n) => n.endsWith('.json'))) {
    try { out[path.basename(f, '.json')] = { record: JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')) }; } catch (e) { out[path.basename(f, '.json')] = { error: `not valid JSON (${e.message})` }; }
  }
  return out;
}

export function run(argv = process.argv.slice(2)) {
  const reportsDir = pathArg('reports', 'EVIDENCE_REPORTS_DIR', path.join(ROOT, 'reports'), argv);
  const artifactsDir = pathArg('artifacts', 'EVIDENCE_ARTIFACTS_DIR', path.join(ROOT, 'artifacts'), argv);
  const date = arg('date', 'EVIDENCE_DATE', today(), argv);
  const outDir = pathArg('out', 'EVIDENCE_OUT_DIR', path.join(SPEC_EVIDENCE, date), argv);
  const manualDir = pathArg('manual', 'EVIDENCE_MANUAL_DIR', path.join(outDir, 'manual'), argv);
  const evidenceRoot = pathArg('root', 'EVIDENCE_ROOT', given('out', 'EVIDENCE_OUT_DIR', argv) ? outDir : SPEC_EVIDENCE, argv);
  const trPath = pathArg('traceability', 'EVIDENCE_TRACEABILITY', path.join(ROOT, 'tests', 'cases', 'traceability.json'), argv);
  const unitDir = pathArg('unit-dir', 'EVIDENCE_UNIT_DIR', path.join(ROOT, 'tests', 'unit'), argv);
  const e2eDir = pathArg('e2e-dir', 'EVIDENCE_E2E_DIR', path.join(ROOT, 'tests', 'e2e'), argv);

  let traceability;
  try { traceability = JSON.parse(fs.readFileSync(trPath, 'utf8')); } catch (e) { console.error(`evidence: cannot read ${trPath}: ${e.message}`); return 2; }
  const problems = validateTraceability(traceability);
  if (problems.length) { console.error(`evidence: traceability.json is invalid:\n  ${problems.join('\n  ')}`); return 2; }

  const unitXml = readText(path.join(reportsDir, 'unit.xml'));
  const e2eText = readText(path.join(reportsDir, 'e2e', 'results.json'));
  const compareText = readText(path.join(reportsDir, 'compare', 'report.json'));
  const historyText = readText(path.join(artifactsDir, 'build-history.jsonl'));
  const manifestText = readText(path.join(artifactsDir, 'dist-manifest.json'));
  const parseJson = (t, what) => { try { return t === null ? null : JSON.parse(t); } catch (e) { console.error(`evidence: ${what} is not valid JSON (${e.message}); treated as missing`); return null; } };

  const e2eRaw = parseJson(e2eText, 'reports/e2e/results.json');
  const site = parseJson(readText(path.join(ROOT, 'src', 'data', 'site.json')), 'site.json');
  const budgetMs = site?.buildTimeBudgetMs ?? 60000;
  const unit = unitXml === null ? null : parseJunit(unitXml);
  const e2e = e2eRaw ? flattenE2E(e2eRaw) : null;
  const history = historyText === null ? null : parseHistory(historyText);
  const manifest = parseJson(manifestText, 'dist-manifest.json');

  const meta = {
    date, generatedAt: new Date().toISOString(), command: 'npm run evidence',
    node: process.version, npm: probe('npm', ['-v'], { shell: process.platform === 'win32' }),
    os: `${os.type()} ${os.release()} ${os.arch()} (${os.version?.() || process.platform})`,
    shell: shellInfo(), browsers: browsersInfo(),
    git: (() => {
      const h = probe('git', ['rev-parse', 'HEAD']);
      const dirty = probe('git', ['status', '--porcelain']);
      return h === 'unavailable' || h === 'not probed' ? h : `${h}${dirty ? ' (working tree has uncommitted changes)' : ''}`;
    })(),
    manifestHash: manifest?.hash || 'NOT RUN (no artifacts/dist-manifest.json)',
  };

  const { rows, counts, attribution } = evaluate({ traceability, unit, e2e, compare: parseJson(compareText, 'compare report'), history, budgetMs, unitDir, e2eDir, env: meta, manual: loadManual(manualDir), evidenceRoot });

  fs.mkdirSync(outDir, { recursive: true });
  const raw = copyRaw(reportsDir, artifactsDir, outDir);
  const missing = raw.filter((f) => !f.present && ['unit.xml', 'e2e/results.json', 'compare/report.json', 'build-history.jsonl'].includes(f.name)).map((f) => f.name);
  const e2eClasses = classCounts(e2e);
  const summary = renderSummary({ rows, counts, meta, raw, history, e2eClasses, budgetMs, attribution });
  fs.writeFileSync(path.join(outDir, 'summary.md'), summary);
  fs.writeFileSync(path.join(outDir, 'environment.json'), JSON.stringify({
    ...meta, budgetMs, statusCounts: counts, missingReports: missing,
    distEdgeBytes: fs.existsSync(path.join(ROOT, 'dist-edge', 'cloudfront-function.js')) ? fs.statSync(path.join(ROOT, 'dist-edge', 'cloudfront-function.js')).size : null,
    buildTimes: (history?.records || []).map((r) => ({ timestamp: r.timestamp, elapsedMs: r.elapsedMs, budgetMs: r.budgetMs, clean: r.clean, idle: r.idle, source: r.source || 'build' })),
    rawReports: raw,
    unitAttribution: attribution ? { ambiguous: attribution.ambiguous, unowned: attribution.unowned } : null,
  }, null, 2) + '\n');

  const code = exitCode(rows, missing);
  console.log(`evidence: ${rows.length} criteria: ` + order.map((s) => `${counts[s] || 0} ${s}`).join(', '));
  if (missing.length) console.log(`evidence: missing reports: ${missing.join(', ')}`);
  console.log(`evidence: wrote ${path.relative(process.cwd(), path.join(outDir, 'summary.md')) || 'summary.md'}; exit ${code}`);
  return code;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  process.exit(run());
}
