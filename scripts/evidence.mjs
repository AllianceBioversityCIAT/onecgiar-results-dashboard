// Evidence pipeline (design 10.3, DD-12; FR-25, FR-27, NFR-10; T-17).
//
// Consolidates the raw reports of one run into
//   docs/specs/changes/results-dashboard-aws-migration/evidence/<YYYY-MM-DD>/
//     summary.md        generated, never hand-edited
//     environment.json  OS, shell, Node, npm, browsers, git commit, dist manifest hash, build times
//     raw/              copies of the raw reports
// using tests/cases/traceability.json (every AC-L, FR and NFR -> tests and report keys).
//
// Status vocabulary (design 10.3): PASSED, FAILED, BLOCKED (reason), NOT RUN, NOT RUN — AWS.
// A criterion is PASSED only when every mapped test is recorded and passed. "Every mapped test" is
// checked against the title scan of the test files (test()/it(), also .skip/.todo/.only: a disabled test is
// still a declared test and needs a record): a unit file's titles inside the
// ref's match, every test of a Playwright spec file (in every configured browser), and, for the
// class-wide checks (FR-22, FR-27), every spec file. A declared test with no record is NOT RUN,
// never PASSED (FR-25 BUT). Limit: tests generated by a loop share one title pattern, so deleting a
// single generated instance (one of many routing cases) is not detected; deleting the whole pattern is.
// Limit: two tests with the same static title in one file share one pattern, so one record satisfies both.
// A recorded unit case belongs to a file only when exactly one file's titles match it; ambiguous
// and unowned cases are listed in the summary and count for no criterion. Weak dynamic titles
// (under 8 literal characters) never decide ownership, yet each one inside a ref's match still needs
// a recorded case: one unowned case claimed by exactly one file's weak pattern counts for that file,
// several claimants mean it counts for none and the pattern stays unmet. For Playwright, weak titles
// are required like any other, because groups are scoped by spec file.
// Precedence when mapped tests disagree: FAILED > NOT RUN > BLOCKED > PASSED.
//
// Exit codes: 0 every criterion is PASSED or BLOCKED (BLOCKED is honest, not a failure);
// 1 at least one criterion is FAILED or NOT RUN, or a report the matrix requires is missing;
// 2 the pipeline itself could not run (unreadable traceability, bad arguments).
//
// Seams (flag, then environment, then default):
//   --reports / EVIDENCE_REPORTS_DIR     reports/             unit.xml, e2e/results.json, compare/report.json
//   --artifacts / EVIDENCE_ARTIFACTS_DIR artifacts/           build-history.jsonl, dist-manifest.json, build-stats.json
//   --out / EVIDENCE_OUT_DIR             <spec>/evidence/<date>
//   --date / EVIDENCE_DATE               today (local)
//   --traceability / EVIDENCE_TRACEABILITY  tests/cases/traceability.json
//   --unit-dir / EVIDENCE_UNIT_DIR       tests/unit           (unit titles are scanned in these files)
//   --e2e-dir / EVIDENCE_E2E_DIR         tests/e2e            (Playwright spec titles are scanned in these files)
// A path given by flag or variable resolves against the current directory (like scripts/compare.mjs);
// the defaults resolve against results-dashboard-static/.
//   --manual / EVIDENCE_MANUAL_DIR       <out>/manual         manual records <criterion-id>.json (T-18/T-19 or a person)
//   --root / EVIDENCE_ROOT               evidence/ (or <out> when --out is given): base of the records' evidenceFiles
//   EVIDENCE_SKIP_PROBES=1               skip spawning npm/git/PowerShell (unit tests)
