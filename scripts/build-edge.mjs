// Step 10 of npm run build (design.md 7.1, 7.3 Adapters, 7.6, 7.7): generates
// dist-edge/cloudfront-function.js, a CDN URL-rewrite function (DD-20: it renders no page and
// reads no data). The file is a verbatim concatenation of
//   1. the `/* @edge */` functions of legacy-compat.core.js,
//   2. rules.core.js,
//   3. the data literal RD_DATA (scripts/site-data.mjs rdData),
//   4. handler(event), the CloudFront adapter.
// Constraints (NFR-07, P-8): <= 10 KB, no require/import/I-O, ES5.1 syntax, strict-mode clean.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { rdData } from './site-data.mjs';

export const EDGE_FILE = 'cloudfront-function.js';
// The documentation says "10 KB" without defining KB (P-8): the stricter 10 000 bytes is used.
export const EDGE_MAX_BYTES = 10000;

export class EdgeBuildError extends Error {
  constructor(details) {
    super(details[0]);
    this.name = 'EdgeBuildError';
    this.details = details;
  }
}

// Handler adapter (design 7.3 Adapters, 7.6). Written in the ES5 subset.
export const HANDLER_SOURCE = `// Form-style decoding for the parsed map (as URLSearchParams); malformed escapes keep the raw text.
function rdDecode(s) {
  try {
    return decodeURIComponent(s.replace(/\\+/g, ' '));
  } catch (e) {
    return s;
  }
}

function rdQueryOf(querystring) {
  var keys = Object.keys(querystring || {});
  var parts = [];
  var params = {};
  for (var i = 0; i < keys.length; i++) {
    var entry = querystring[keys[i]];
    var list = entry.multiValue && entry.multiValue.length > 0 ? entry.multiValue : [entry];
    for (var j = 0; j < list.length; j++) {
      parts.push(keys[i] + '=' + list[j].value);
    }
    params[rdDecode(keys[i])] = rdDecode(list[list.length - 1].value);
  }
  return { query: parts.join('&'), params: params };
}

function rdResponse(status, description, headers, body) {
  var response = { statusCode: status, statusDescription: description, headers: headers };
  if (body) { response.body = body; }
  return response;
}

function handler(event) {
  var request = event.request;
  var q = rdQueryOf(request.querystring);
  var host = request.headers && request.headers.host ? request.headers.host.value : '';
  var result = resolve({
    method: request.method,
    host: host,
    path: request.uri,
    query: q.query,
    params: q.params
  }, 'edge');
  if (result.type === 'rewrite') {
    request.uri = '/' + result.file;
    return request;
  }
  if (result.type === 'redirect') {
    return rdResponse(301, 'Moved Permanently', { location: { value: result.location } });
  }
  if (result.type === 'badRequest') {
    return rdResponse(400, 'Bad Request', { 'content-type': { value: 'text/plain' } }, 'Bad Request');
  }
  if (result.type === 'methodNotAllowed') {
    return rdResponse(405, 'Method Not Allowed',
      { allow: { value: 'GET, HEAD' }, 'content-type': { value: 'text/plain' } }, 'Method Not Allowed');
  }
  if (result.type === 'notFound') {
    request.uri = '/__rd_not_found__';
    return request;
  }
  return request;
}
`;

const toLf = (s) => s.replace(/\r\n?/g, '\n');

// The `/* @edge */` marked top-level functions of a core source, verbatim, in file order.
export function extractEdgeFunctions(coreSource) {
  const src = toLf(coreSource);
  const out = [];
  const re = /^\/\* @edge \*\/\nfunction [A-Za-z_$][\w$]*[\s\S]*?\n\}\n/gm;
  for (const m of src.matchAll(re)) out.push(m[0].replace(/^\/\* @edge \*\/\n/, ''));
  return out;
}

// Behavior-preserving strip of whole `//` comment lines and blank lines (allowed by design 7.1
// only when the budget is exceeded; the cores keep comments only as whole lines).
export function stripComments(source) {
  return toLf(source).split('\n').filter((l) => l.trim() !== '' && !/^\s*\/\//.test(l)).join('\n') + '\n';
}

export function assembleEdge({ legacySource, rulesSource, data, strip = false }) {
  const edgeFns = extractEdgeFunctions(legacySource);
  if (edgeFns.length === 0) throw new EdgeBuildError(['no /* @edge */ function found in legacy-compat.core.js']);
  const parts = [
    '// Generated by scripts/build-edge.mjs. Do not edit. CloudFront Function (cloudfront-js-2.0): URL rewrite only.',
    edgeFns.join('\n'),
    toLf(rulesSource).trimEnd() + '\n',
    `var RD_DATA = ${JSON.stringify(data)};\n`,
    HANDLER_SOURCE,
  ];
  const text = parts.join('\n');
  return strip ? stripComments(text) : text;
}

// Forbidden constructs (NFR-07, Y-2).
const FORBIDDEN = [
  [/\brequire\s*\(/, 'require()'],
  [/^\s*import\b|\bimport\s*\(/m, 'import'],
  [/^\s*export\b/m, 'export'],
  [/\bmodule\.exports\b|\bexports\./, 'module.exports'],
  [/\bprocess\b/, 'process'],
  [/\b(?:fs|child_process)\b\s*[.(]|['"]node:/, 'Node module or API'],
  [/\beval\s*\(/, 'eval'],
  [/\bnew\s+Function\b|\bFunction\s*\(/, 'Function constructor'],
  [/\b(?:setTimeout|setInterval|setImmediate|clearTimeout)\b/, 'timers'],
  [/\b(?:fetch|XMLHttpRequest|WebSocket)\b/, 'network API'],
  [/\b(?:window|document|navigator|localStorage)\b/, 'browser global'],
  [/\b(?:Buffer|URLSearchParams|URL)\b/, 'Node/Web global outside the runtime'],
  // Stricter than the runtime on purpose: Date and Math.random would break determinism.
  [/\bDate\b|Math\.random/, 'clock or randomness'],
  [/<\?php|<\?=/, 'PHP marker'],
];

// Returns a list of findings (empty = clean).
export function checkEdgeSource(source) {
  const findings = [];
  const bytes = Buffer.byteLength(source, 'utf8');
  if (bytes > EDGE_MAX_BYTES) findings.push(`size ${bytes} bytes exceeds ${EDGE_MAX_BYTES}`);
  // Whole-line // comments are prose, not constructs: blank them (keeping line numbers).
  const code = source.split('\n').map((l) => (/^\s*\/\//.test(l) ? '' : l)).join('\n');
  for (const [re, name] of FORBIDDEN) {
    const m = re.exec(code);
    if (m) {
      const line = code.slice(0, m.index).split('\n').length;
      findings.push(`forbidden construct ${name} at line ${line}: ${m[0].trim()}`);
    }
  }
  try {
    // Strict mode is always on in cloudfront-js-2.0 (P-8); parse only, never run.
    new vm.Script(`"use strict";\n${source}`, { filename: EDGE_FILE });
  } catch (e) {
    findings.push(`syntax: ${e.message}`);
  }
  return findings;
}

// Builds <edgeDir>/cloudfront-function.js. Returns { file, bytes, stripped }.
export function buildEdge({ srcDir, edgeDir, site }) {
  const legacySource = fs.readFileSync(path.join(srcDir, 'runtime', 'legacy-compat.core.js'), 'utf8');
  const rulesSource = fs.readFileSync(path.join(srcDir, 'routing', 'rules.core.js'), 'utf8');
  const data = rdData(site);
  let stripped = false;
  let text = assembleEdge({ legacySource, rulesSource, data });
  if (Buffer.byteLength(text, 'utf8') > EDGE_MAX_BYTES) {
    stripped = true;
    text = assembleEdge({ legacySource, rulesSource, data, strip: true });
  }
  const findings = checkEdgeSource(text);
  if (findings.length > 0) throw new EdgeBuildError([`${findings.length} finding(s) in ${EDGE_FILE}`, ...findings]);
  fs.mkdirSync(edgeDir, { recursive: true });
  const file = path.join(edgeDir, EDGE_FILE);
  fs.writeFileSync(file, text);
  return { file, bytes: Buffer.byteLength(text, 'utf8'), stripped };
}
